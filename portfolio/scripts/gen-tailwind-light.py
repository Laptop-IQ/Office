#!/usr/bin/env python3
"""
Generates src/theme.tailwind-light.css

The app's Tailwind pages were designed for dark backgrounds (slate-950 pages,
text-white, bg-white/5 overlays, text-violet-300 …). In the light theme we
flip every Tailwind colour scale (50 <-> 950, 100 <-> 900 …) and map `white`
to a dark ink colour. Because Tailwind v4 utilities read these values from
CSS variables, overriding the variables is enough – no class names change.

Run:  python3 scripts/gen-tailwind-light.py
"""
import re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
theme = (root / "node_modules/tailwindcss/theme.css").read_text()

shades = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]
colors = {}
for fam, shade, val in re.findall(r"--color-([a-z]+)-(\d+):\s*([^;]+);", theme):
    colors.setdefault(fam, {})[int(shade)] = val.strip()

NEUTRAL = {"slate", "gray", "zinc", "neutral", "stone"}

def source_shade(fam, s):
    """Which shade of the *original* scale supplies value `s` in light mode."""
    if fam in NEUTRAL:
        # full flip: 50<->950, 100<->900 …  (surfaces, borders, text all flip)
        return shades[len(shades) - 1 - shades.index(s)]
    # chromatic scales: keep the vivid mid-tones so buttons / badges stay
    # punchy, flip the light text shades to darker ones and the dark
    # background shades to pale tints.
    if s in (500, 600):
        return s
    return shades[len(shades) - 1 - shades.index(s)]

out = []
out.append("/* AUTO-GENERATED by scripts/gen-tailwind-light.py – do not edit by hand. */")
out.append("/* Light theme: neutrals fully inverted, chromatic scales keep 500/600. */")
out.append('html[data-theme="light"] {')
out.append("  --color-white: #0b1220; /* \"white\" text / overlays become dark ink */")
for fam in sorted(colors):
    scale = colors[fam]
    if not all(s in scale for s in shades):
        continue
    for s in shades:
        out.append(f"  --color-{fam}-{s}: {scale[source_shade(fam, s)]};")
out.append("}")
# White text on vivid fills --------------------------------------------------
# "text-white" (and inherited white text) is mapped to dark ink in light mode so
# normal copy stays readable. Anything sitting on a solid vivid background
# (buttons, gradient CTAs, badges) must stay white. Uses whole-token matching
# ([class~=...]) so tinted (bg-x/20) and hover:/focus: variants don't match.
chroma = [f for f in sorted(colors) if f not in NEUTRAL]
solid = []
for fam in chroma:
    if fam in ("yellow", "amber", "lime"):
        continue  # light fills – keep dark text on them
    for sh in (500, 600, 700):
        solid.append(f'[class~="bg-{fam}-{sh}"]')
        solid.append(f'[class~="from-{fam}-{sh}"]')
out.append("")
out.append("/* White text on solid vivid fills */")
out.append('html[data-theme="light"] :is(')
out.append("  " + ",\n  ".join(solid))
out.append(')\n:not([class~="text-black"]):not([class~="text-slate-900"]):not([class~="text-slate-950"]) {'.replace(")\n:", "):"))
out.append("  color: #ffffff;")
out.append("}")
(root / "src/theme.tailwind-light.css").write_text("\n".join(out) + "\n")
print("wrote", len(out), "lines")
