/** Renders a Remix icon for a stored emoji key. Elements and unknown text pass through. */
export function Ico({ v, size = "1em", className, style }) {
  if (typeof v !== "string") return v ?? null;
  const Cmp = MAP[v.replace(/\uFE0F/g, "").trim()];
  if (!Cmp) return v;
  return <Cmp size={size} className={className} style={style} aria-hidden="true" />;
}
